<#
.SYNOPSIS
    Creates the patched work tree for FileZilla and records a pristine baseline commit.

.DESCRIPTION
    The upstream tree (default <your profile>\source\repos\filezilla-<version>) is left
    completely untouched. This copies it to C:\fzdark\work\filezilla-<version>, turns
    that copy into a git repository, and commits the pristine state as a single
    "baseline" commit.

    Every change we make then lands as its own commit on top, so the whole series
    can be exported with `git format-patch` into the patches\ directory beside this
    script and re-applied to a future FileZilla release with `git am -3`. That is
    what keeps the port maintainable.

    .gitignore covers autotools build output so `git status` stays readable while
    FileZilla is being compiled in-tree.

.PARAMETER Source
    Pristine upstream tree. Default: <your profile>\source\repos\filezilla-<version>

. PARAMETER Recreate
    Delete and re-create the work tree. Use this to throw away all patches and
    start again from pristine upstream.
#>
[CmdletBinding()]
param(
    # Left empty so it can be derived below; param defaults run before the
    # dot-source that supplies the version.
    [string]$Source,
    [switch]$Recreate
)

$ErrorActionPreference = 'Stop'

. (Join-Path (Split-Path -Parent $PSScriptRoot) 'versions.ps1')

if (-not $Source) { $Source = Join-Path $env:USERPROFILE "source\repos\filezilla-$FzVersion" }

$git = 'C:\Program Files\Git\cmd\git.exe'
$work = "C:\fzdark\work\filezilla-$FzVersion"

# The repo is relocatable, so the patches directory is resolved from this script's
# own location instead of being hard-coded to an absolute build path.
$patches = Join-Path (Split-Path -Parent $PSScriptRoot) 'patches'

if (-not (Test-Path $git)) { throw "git not found at $git" }
if (-not (Test-Path (Join-Path $Source 'configure.ac'))) { throw "no configure.ac in $Source" }

if (Test-Path $work) {
    if (-not $Recreate) {
        Write-Host "work tree already exists at $work"
        # Write-Host does not concatenate with '+' - the operator is passed through
        # as a literal argument, which rendered as "current branch : + baseline".
        # Parentheses are required to force real string concatenation.
        Write-Host ("  current branch : " + ((& $git -C $work rev-parse --abbrev-ref HEAD) -join ''))
        Write-Host ("  commits on top : " + ((& $git -C $work rev-list --count HEAD) -join '') + ' (including baseline)')
        Write-Host ("  patches exported: " + ((Get-ChildItem $patches -Filter '*.patch' -ErrorAction SilentlyContinue) | Measure-Object).Count)
        Write-Host ''
        Write-Host 'Use -Recreate to discard local changes and start from pristine upstream again.'
        return
    }
    Write-Host "Removing existing work tree $work"
    Remove-Item $work -Recurse -Force
}

Write-Host "Copying pristine tree..."
Write-Host "  from $Source"
Write-Host "  to   $work"
New-Item -ItemType Directory -Force -Path (Split-Path $work) | Out-Null
& robocopy.exe $Source $work /E /NFL /NDL /NJH /NJS /NP /XD '.git' | Out-Null
# robocopy exit codes < 8 are success; 1 means "files copied".
if ($LASTEXITCODE -ge 8) { throw "robocopy failed with exit code $LASTEXITCODE" }

Write-Host ''
Write-Host 'Writing .gitignore...'
$gitignore = @'
# autotools / automake build output
Makefile
Makefile.in
!Makefile.am
config.h
config.h.in
!config.h.in
config.log
config.status
config.cache
stamp-h1
.deps/
.libs/
*.o
*.lo
*.la
*.lai
*.a
*.exe
*.obj
*.dll

# generated by configure
data/install.nsi
data/makezip.sh

# locales build output
locales/*/LC_MESSAGES/*.mo

# our build logs
*.log
'@
Set-Content -Path (Join-Path $work '.gitignore') -Value $gitignore -Encoding UTF8

Write-Host 'Initialising git repository...'
& $git -C $work init --quiet --initial-branch=main
& $git -C $work config user.email 'fzdark@localhost'
& $git -C $work config user.name  'FileZilla dark mode port'
& $git -C $work config core.autocrlf false

& $git -C $work add -A
# Double-quoted here-string so the pinned version is interpolated rather than typed
# out; a stale release number in the baseline commit is a needless source of doubt
# when auditing the tree the patch series is applied to.
& $git -C $work commit --quiet -m @"
baseline: pristine FileZilla $FzVersion release tarball

Unmodified upstream sources, used as the base for the dark-mode patch series.
Do not edit; every change belongs in its own commit on top of this one.
"@

$count = ((& $git -C $work rev-list --count HEAD) -join '')
$files = ((& $git -C $work ls-files | Measure-Object).Count)
Write-Host ''
Write-Host "work tree ready: $work"
Write-Host "  commits      : $count"
Write-Host "  tracked files: $files"
Write-Host ''
Write-Host 'Next: apply the patches, then export with'
# git wants forward slashes even on Windows, and it must not quote the path itself.
Write-Host "  git -C $work format-patch -o $($patches -replace '\\', '/') main"
